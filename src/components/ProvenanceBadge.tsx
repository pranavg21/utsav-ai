/**
 * @fileoverview Provenance badge component making GenAI usage vs deterministic fallbacks transparent.
 */

import React from 'react';
import { Sparkles, Shield } from 'lucide-react';
import type { ProvenanceBadgeData } from '../types/plannerExtended';

interface BadgeProps {
  readonly provenance: ProvenanceBadgeData;
  readonly className?: string;
}

const GEMINI_BADGE_STYLE =
  'inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-medium ' +
  'bg-emerald-500/15 text-emerald-400 border border-emerald-500/30';

const FALLBACK_BADGE_STYLE =
  'inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-medium ' +
  'bg-amber-500/15 text-amber-400 border border-amber-500/30';

export const ProvenanceBadge: React.FC<BadgeProps> = React.memo(({ provenance, className = '' }) => {
  if (provenance.source === 'gemini') {
    return (
      <span
        aria-label="Intelligence provenance: Generated by Gemini 2.5 Flash"
        className={`${GEMINI_BADGE_STYLE} ${className}`.trim()}
      >
        <Sparkles className="w-3.5 h-3.5 text-emerald-400" aria-hidden="true" />
        Generated by {provenance.model ?? 'Gemini 2.5 Flash'}
      </span>
    );
  }

  const reasonLabels: Record<NonNullable<ProvenanceBadgeData['reason']>, string> = {
    'no-api-key': 'no API key configured',
    'quota-exceeded': 'API quota exceeded',
    'invalid-output': 'schema validation fallback',
    'timeout': 'timeout (15s ceiling)',
    'offline': 'offline mode active',
  };

  const reasonText = provenance.reason ? reasonLabels[provenance.reason] : 'resilience engine';

  return (
    <span
      aria-label={`Intelligence provenance: Deterministic fallback due to ${reasonText}`}
      className={`${FALLBACK_BADGE_STYLE} ${className}`.trim()}
    >
      <Shield className="w-3.5 h-3.5 text-amber-400" aria-hidden="true" />
      Deterministic fallback (reason: {reasonText})
    </span>
  );
});
ProvenanceBadge.displayName = 'ProvenanceBadge';

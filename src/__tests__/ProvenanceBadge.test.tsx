/**
 * @fileoverview Unit tests for ProvenanceBadge component verifying AI vs deterministic badges.
 */

import React from 'react';
import { describe, it, expect } from 'vitest';
import { render, screen } from '@testing-library/react';
import { ProvenanceBadge } from '../components/ProvenanceBadge';

describe('ProvenanceBadge component', () => {
  it('renders Gemini generated badge with custom model', () => {
    render(<ProvenanceBadge provenance={{ source: 'gemini', model: 'gemini-2.5-flash' }} />);
    expect(screen.getByText('Generated by gemini-2.5-flash')).toBeDefined();
  });

  it('renders deterministic fallback badge with classified reasons', () => {
    const { rerender } = render(
      <ProvenanceBadge provenance={{ source: 'deterministic', reason: 'no-api-key' }} />
    );
    expect(screen.getByText(/no API key configured/i)).toBeDefined();

    rerender(<ProvenanceBadge provenance={{ source: 'deterministic', reason: 'quota-exceeded' }} />);
    expect(screen.getByText(/API quota exceeded/i)).toBeDefined();

    rerender(<ProvenanceBadge provenance={{ source: 'deterministic', reason: 'invalid-output' }} />);
    expect(screen.getByText(/schema validation fallback/i)).toBeDefined();

    rerender(<ProvenanceBadge provenance={{ source: 'deterministic', reason: 'timeout' }} />);
    expect(screen.getByText(/timeout \(15s ceiling\)/i)).toBeDefined();
  });
});

